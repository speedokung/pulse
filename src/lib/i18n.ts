// Thai first, English second. `t("key", { n: 2 })` fills {n}.
// The whole app re-renders from <App> when the language changes, so a module-level value is enough.
export type Lang = "th" | "en";

const read = (): Lang => {
  try { const v = localStorage.getItem("pulse.uiLang"); if (v === "th" || v === "en") return v; } catch { /* private mode */ }
  return "th"; // starting in Thailand
};
let LANG: Lang = read();
export const getLang = () => LANG;
export function setLang(l: Lang) {
  LANG = l;
  try { localStorage.setItem("pulse.uiLang", l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}
document.documentElement.lang = LANG;

